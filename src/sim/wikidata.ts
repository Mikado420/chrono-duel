/* Writes src/wiki/envdata.ts, the rated play facts the strategy wiki shows: `npm run wiki:data`.
 * Only counts and deck ids leave the roster: the rivals' names must never reach the wiki (its bundle does not import
 * the roster for the same reason). Run it again after changing the roster. */
import { writeFileSync } from 'node:fs';
import { ROSTER, deckAvailable } from '../meta/roster';
import { TIERS, tierOf } from '../meta/rating';
import { ROSTER_DECKS, canonDeck } from './rosterDecks';

const builds: Record<string, [number, number]> = {};
const bands: Record<string, { lv: [number, number]; rating: [number, number]; rivals: number; decks: Record<string, number> }> = {};
const lvs: Record<number, number> = {};
for (const r of ROSTER) {
  lvs[r.lv] = (lvs[r.lv] ?? 0) + 1;
  const band = tierOf(r.rating).tier.id;
  const b = (bands[band] ??= { lv: [r.lv, r.lv], rating: [r.rating, r.rating], rivals: 0, decks: {} });
  b.lv = [Math.min(b.lv[0], r.lv), Math.max(b.lv[1], r.lv)];
  b.rating = [Math.min(b.rating[0], r.rating), Math.max(b.rating[1], r.rating)];
  b.rivals++;
  for (const d of [r.deck, r.sub].map(canonDeck)) {
    if (!deckAvailable(d) || !ROSTER_DECKS.some((x) => x.id === d)) continue;
    const l = builds[d];
    builds[d] = l ? [Math.min(l[0], r.lv), Math.max(l[1], r.lv)] : [r.lv, r.lv];
    b.decks[d] = (b.decks[d] ?? 0) + 1;
  }
}
const order = Object.fromEntries(TIERS.map((t, i) => [t.id, i]));
const out = `/* Generated by \`npm run wiki:data\` (src/sim/wikidata.ts) — do not edit by hand. Rated play: counts and deck ids only. */
/** Roster build id → [lowest, highest] rival Lv that brings it. */
export const BUILD_LV: Record<string, [number, number]> = ${JSON.stringify(builds)};
/** Rivals per Lv. */
export const LV_COUNT: Record<number, number> = ${JSON.stringify(lvs)};
/** Per rank (of the rival's rating): the rivals' Lv and rating range, how many rivals, and how many bring each build (main or second deck). */
export const BAND_DECKS: Record<string, { lv: [number, number]; rating: [number, number]; rivals: number; decks: Record<string, number> }> = ${JSON.stringify(Object.fromEntries(Object.entries(bands).sort((a, b) => order[a[0]] - order[b[0]])))};
`;
writeFileSync('src/wiki/envdata.ts', out);
console.log(`src/wiki/envdata.ts: ${Object.keys(builds).length} builds, ${Object.keys(bands).length} ranks, ${ROSTER.length} rivals`);
