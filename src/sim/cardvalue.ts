/* 入れ替え試験の結果から src/wiki/cardvalue.ts を書く: `npx tsx src/sim/cardvalue.ts <results.jsonl>`
 * Each line of the results: { card, build, n, orig, swap, value } — one card in one roster build, swapped for a plain
 * 2-cost 2/2, both lists playing the same n games (same seeds) against the whole roster (see the 攻略wiki).
 * A card's value is the average over its builds of (win rate with it − win rate without it), in points. */
import { readFileSync, writeFileSync } from 'node:fs';

const proc = process as unknown as { argv: string[]; env: Record<string, string | undefined> };
const rows = readFileSync(proc.argv[2], 'utf8').trim().split('\n').filter(Boolean).map((l) => JSON.parse(l) as { card: string; build: string; n: number; value: number });
const by: Record<string, { v: number[]; n: number }> = {};
for (const r of rows) { const x = (by[r.card] ??= { v: [], n: r.n }); x.v.push(r.value); }
const cards = Object.fromEntries(Object.entries(by).map(([id, x]) => [id, [Math.round((1000 * x.v.reduce((a, b) => a + b, 0)) / x.v.length) / 10, x.v.length] as [number, number]]));
const n = rows[0]?.n ?? 0;
const date = new Date(Date.now() + 9 * 3_600_000).toISOString().slice(0, 10);
writeFileSync('src/wiki/cardvalue.ts', `/* Generated by \`npx tsx src/sim/cardvalue.ts\` — do not edit by hand. 入れ替え試験（${proc.env.LV ?? 'Lv4'}・名簿の全デッキと${n}戦ずつ、同じ組み合わせで比べる）。 */
export const CARD_VALUE: { date: string; games: number; level: string; cards: Record<string, [number, number]> } = ${JSON.stringify({ date, games: n, level: proc.env.LV ?? 'Lv4', cards })};
`);
console.log(`src/wiki/cardvalue.ts: ${Object.keys(cards).length} cards`);
